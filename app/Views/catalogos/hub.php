        </h3>
        <p style="color: var(--neutral-700); line-height: 1.8; margin-bottom: 0.5rem;">
          Define los 3 tipos de reportes obligatorios: Operaciones Relevantes, Operaciones Inusuales, Operaciones Internas Preocupantes.
